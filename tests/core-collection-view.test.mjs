import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const html=readFileSync(new URL('../src/ui.html',import.meta.url),'utf8');
const script=html.match(/<script>([\s\S]*)<\/script>/)[1];
const esc=s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const webURL=s=>{try{const u=new URL(s);return ['http:','https:'].includes(u.protocol)?u.href:null}catch{return null}};
const link=(u,label)=>'<a href="'+esc(u)+'">'+esc(label)+'</a>';
const context=vm.createContext({URL,Date,esc,link,webURL});
vm.runInContext(script.slice(script.indexOf('function recordedMJL('),script.indexOf('function journalInformation(')),context);
const render=report=>{context.r=report;return vm.runInContext('coreCollectionPanel(r)',context)};
const base={issn:['1572-8196','1022-0038'],electronicISSN:'1572-8196',index:'SCIE',indexEvidence:'Science Citation Index Expanded',indexAuthority:'Publisher',indexSource:'https://link.springer.com/journal/11276',checked:'2026-11-05'};
const publisher=render(base);
assert.match(publisher,/Web of Science Core Collection/);
assert.match(publisher,/Science Citation Index Expanded \(SCIE\)/);
assert.match(publisher,/https:\/\/link.springer.com\/journal\/11276/);
assert.match(publisher,/Not directly verified/);
assert.match(publisher,/issn=1572-8196/);
const direct=render({...base,clarivateCheck:{index:'SCIE',checkedISSN:'1572-8196',source:'https://mjl.clarivate.com/',identityMatched:true,evidence:'Science Citation Index Expanded',checked:'2026-11-05'}});
assert.match(direct,/Recorded for this journal and ISSN/);
assert.doesNotMatch(direct,/Not directly verified/);
const unknown=render({issn:[],index:'UNKNOWN'});assert.match(unknown,/Coverage not yet verified/);assert.doesNotMatch(unknown,/SCIE coverage found/);
const excluded=render({...base,index:'ESCI',indexEvidence:'Emerging Sources Citation Index'});assert.match(excluded,/Emerging Sources Citation Index \(ESCI\)/);assert.match(excluded,/Excluded/);
const untrusted=render({...base,indexEvidence:'<script>alert(1)</script>'});assert.doesNotMatch(untrusted,/<script>/);
console.log('Visible Core Collection section, legacy reports, publisher/direct Clarivate distinction and exclusion rendering passed.');
